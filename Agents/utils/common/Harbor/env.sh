harbor_run_name_component() {
  local value
  value="$(printf '%s' "$1" |
    LC_ALL=C tr -cs 'A-Za-z0-9_-' '-' |
    sed 's/^-*//; s/-*$//' |
    cut -c1-"${2:-32}")"
  value="${value#-}"
  value="${value%-}"
  printf '%s\n' "${value:-run}"
}

